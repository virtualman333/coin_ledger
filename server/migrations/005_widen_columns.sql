-- 005 · 放宽超长字符串列（widen columns）（MySQL 5.7 默认 STRICT_TRANS_TABLES 迁移阻断修复）
--
-- 问题：001 建表时 edge VARCHAR(32)，但存量 coins.json 有 9 条公告原文超过 32 字：
--       no=16(41) / 18(40) / 20(36) / 21(36) / 22(36) / 23(36)
--       no=25(42) / 29(41) / 34(41)
--       例：no=25 = 侧边缘滚字图案是"中国 "的汉语拼音文字"ZHONGGUO"及 3 个五角星，共两组
-- 表现：原版 MySQL 5.7.40（未改 sql_mode）执行 migrate:catalog --apply 直接报
--       `Data too long for column 'edge' at row 1`，事务回滚、cl_coins=0 行。
--
-- 为什么新增迁移而不是改 001：runner 用 checksum 记账，改历史迁移会让**已经建过表**
-- 的环境全部报「checksum 与库内记录不一致」。新增前向迁移对全新库和已有库都成立：
--   · 全新库：001 先建 VARCHAR(32)，本迁移立刻放宽到 128；
--   · 已有库：001..004 跳过（checksum 不变），本迁移执行一次即可。
-- 语义：只放宽列宽，不改数据、不改 no、不动其他列；重复执行结果一致。
-- =====================================================================

-- @@

ALTER TABLE cl_coins
  MODIFY COLUMN edge VARCHAR(128) NULL COMMENT '边齿/边部图案（央行公告原文，最长 42 字符）';
