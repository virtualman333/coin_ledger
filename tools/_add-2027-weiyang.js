const NEW_ITEM = {
  key: 'G202702',
  code: 'G202702',
  name: '2027中国丁未（羊）年贵金属纪念币',
  pieces: 11,
  release: '2026年11月27日',
  announce: ANNOUNCE,
};

const file = config.PLAN_PM_FILE;
const doc = JSON.parse(fs.readFileSync(file, 'utf8'));

const dup = [];
doc.years.forEach(function (y) {
  (y.items || []).forEach(function (it) {
    if (it.key === NEW_ITEM.key || it.name === NEW_ITEM.name) dup.push(y.year + '/' + it.key);
  });
});
if (dup.length) {
  console.error('已存在同 key/同名项目，终止：' + dup.join(', '));
  process.exit(1);
}

let y2027 = doc.years.filter(function (y) { return Number(y.year) === 2027; })[0];
if (!y2027) {
  y2027 = { year: 2027, items: [] };
  doc.years.push(y2027);
}
// items 按发行日期倒序（最新在前），与既有年度一致
y2027.items.unshift(NEW_ITEM);

doc.updated = '2026-11-21';

const norm = svc.normalizePlan(doc);
if (norm.error) {
  console.error('校验失败：' + norm.error);
  process.exit(1);
}
fs.writeFileSync(file, JSON.stringify(norm.plan, null, 1) + '\n', 'utf8');

const items = norm.plan.years.reduce(function (a, y) { return a + y.items.length; }, 0);
console.log('OK → ' + path.basename(file) + '：' + norm.plan.years.length + ' 个年度 / ' + items + ' 个项目');
